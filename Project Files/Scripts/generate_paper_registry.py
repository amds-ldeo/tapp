HEADER = FIXED_COLS + TECH_COLS


def build():
    out = [HEADER]
    for p in papers:
        missing = [c for c in HEADER if c not in p]
        if missing:
            raise SystemExit(f"{p['Citation Key']}: missing {missing}")
        extra = [c for c in p if c not in HEADER]
        if extra:
            raise SystemExit(f"{p['Citation Key']}: keys not in HEADER {extra}")
        blank = [c for c in TECH_COLS if not str(p[c]).strip()]
        if blank:
            raise SystemExit(f"{p['Citation Key']}: blank cells in {blank}")
        bad = [c for c in TECH_COLS if p[c] not in ('Detailed', 'Brief', 'N')]
        if bad:
            raise SystemExit(f"{p['Citation Key']}: non-label values in {bad}")
        out.append([p[c] for c in HEADER])
    return out


